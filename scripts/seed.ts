import { hashPassword } from 'better-auth/crypto';
import { drizzle } from 'drizzle-orm/postgres-js';
import postgres from 'postgres';
import * as schema from '../src/lib/server/db/schema.ts';

if (!process.env.DATABASE_URL) throw new Error('DATABASE_URL is not set');
const client = postgres(process.env.DATABASE_URL);
const db = drizzle(client, { schema });
import { account, member, organization, user } from '../src/lib/server/db/auth.schema.ts';
import { plan, subscription, usageRecord } from '../src/lib/server/db/billing.schema.ts';
import { project } from '../src/lib/server/db/app.schema.ts';
import { notification } from '../src/lib/server/db/notification.schema.ts';

async function seed() {
	const email = 'seed@example.com';
	const userId = 'seed_user';
	const organizationId = 'seed_org';
	const password = await hashPassword('Seed.Pass.123!');
	const now = new Date();

	await db
		.insert(user)
		.values({
			id: userId,
			name: 'Seed User',
			email,
			emailVerified: true,
			image: null,
			createdAt: now,
			updatedAt: now
		})
		.onConflictDoNothing();

	await db
		.insert(account)
		.values({
			id: 'seed_account',
			accountId: email,
			providerId: 'credential',
			userId,
			password,
			createdAt: now,
			updatedAt: now
		})
		.onConflictDoNothing();

	await db
		.insert(organization)
		.values({
			id: organizationId,
			name: 'Seed Org',
			slug: 'seed-org',
			createdAt: now
		})
		.onConflictDoNothing();

	await db
		.insert(member)
		.values({
			id: 'seed_member',
			organizationId,
			userId,
			role: 'owner',
			createdAt: now
		})
		.onConflictDoNothing();

	await db
		.insert(plan)
		.values({
			id: 'seed_plan',
			key: 'seed-pro',
			name: 'Seed Pro',
			description: 'Demo plan for local development',
			priceMonthlyCents: 2900,
			features: { apiAccess: true, auditLog: false },
			limits: { projects: 25 },
			isActive: true,
			sortOrder: 1
		})
		.onConflictDoNothing();

	await db
		.insert(subscription)
		.values({
			id: 'seed_subscription',
			organizationId,
			planId: 'seed_plan',
			status: 'active',
			provider: 'console',
			seats: 5,
			currentPeriodStart: now,
			currentPeriodEnd: new Date(now.getTime() + 30 * 24 * 60 * 60 * 1000),
			createdAt: now,
			updatedAt: now
		})
		.onConflictDoNothing();

	await db
		.insert(usageRecord)
		.values({
			id: 'seed_usage',
			organizationId,
			subscriptionId: 'seed_subscription',
			metric: 'projects',
			quantity: 1,
			periodStart: now,
			periodEnd: new Date(now.getTime() + 30 * 24 * 60 * 60 * 1000),
			updatedAt: now
		})
		.onConflictDoNothing();

	await db
		.insert(project)
		.values({
			id: 'seed_project',
			organizationId,
			name: 'Sample project',
			description: 'Generated by bun run db:seed',
			createdAt: now,
			updatedAt: now
		})
		.onConflictDoNothing();

	await db
		.insert(notification)
		.values({
			id: 'seed_notification',
			audience: 'user',
			userId,
			title: 'Welcome',
			body: 'Your seed workspace is ready.',
			href: '/dashboard/projects',
			data: {},
			createdAt: now
		})
		.onConflictDoNothing();

	console.log(`Seeded ${email} / Seed.Pass.123! into ${organizationId}`);
	await client.end();
}

seed().catch(async (error) => {
	console.error(error);
	await client.end();
	process.exit(1);
});
